-- P1-1b1：角色表。只建表，不建数据库，不改 schema 属主。
--
-- 种族只存出身编号与外观：这张表里没有任何属性列，种族也就无从影响数值。
-- 职业与分支可写；分支允许为空（15 级一转才定，转身规则不在这张卡的库里）。
-- 主线场次与立仙/立魔创建时为空，服务端不写，后续主线才填。
CREATE TABLE IF NOT EXISTS "角色".character (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account     text        NOT NULL REFERENCES "角色".account (account),
    name        text        NOT NULL,
    race        text        NOT NULL,
    appearance  jsonb       NOT NULL DEFAULT '{}'::jsonb,
    class_id    text        NOT NULL,
    branch      text,
    level       integer     NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 100),
    realm       text        NOT NULL DEFAULT '炼体',
    main_stage  integer,
    alignment   text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- 同一个账号下名字不重，换个账号可以同名。
CREATE UNIQUE INDEX IF NOT EXISTS character_account_name
    ON "角色".character (account, name);

-- P1-2a：疲劳与周份额。主线进本不改这两个值，有了可比的东西才谈得上「不变」。
-- 深渊按人数扣疲劳、巢穴占周份额分别在 P1-2b1、P1-2c。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS fatigue integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_fatigue_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_fatigue_non_negative CHECK (fatigue >= 0);

ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS weekly_share integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_weekly_share_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_weekly_share_non_negative CHECK (weekly_share >= 0);

-- P1-2b1：疲劳是「一天」的上限，不是永久累计。记最后一次结算落在哪一天，
-- 进本时发现日界变了就先归零。日界按数据库 current_date，不另设时区配置。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS fatigue_day date NOT NULL DEFAULT CURRENT_DATE;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_fatigue_daily_cap;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_fatigue_daily_cap CHECK (fatigue <= 6000);

-- P1-2c：周份额是「这一周」的，记最后一次结算落在哪一个周首。
-- 周界按数据库 date_trunc('week', current_date)（周一为一周之始），不另设时区配置。
-- weekly_share 记的是「本周已经用掉的单人份」，每周上限 12 由 config/dungeons.json
-- 的 weekly_share_cap 给，库层只守非负：数值只有一个正本，改配置不用改约束。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS weekly_share_day date
    NOT NULL DEFAULT date_trunc('week', CURRENT_DATE::timestamp)::date;

-- P1-2d：当前等级已有经验。等级经验只由 SettleExp 这一笔写入，
-- 到 level_cap 之后不再升级；库层仍用 CHECK (level BETWEEN 1 AND 100) 兜底。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS exp bigint NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_exp_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_exp_non_negative CHECK (exp >= 0);
