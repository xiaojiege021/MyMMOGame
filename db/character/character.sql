-- === D8：主迁移补全量（账号表）===
-- 与 db/character/account.sql 是同一份；网关先跑 account.sql，这里再放一份，
-- 让只跑主迁移也能建齐角色 schema（character / character_slot 都带账号外键）。
-- P1-1a1：账号表。只建表，不建数据库，不改 schema 属主。
-- 口令只存哈希、盐和迭代次数，不存明文；改口令策略不用改表结构。
-- 账号按原样匹配（不折叠大小写），注册那一行再定账号规则。
CREATE TABLE IF NOT EXISTS "角色".account (
    account        text        PRIMARY KEY,
    password_hash  bytea       NOT NULL,
    password_salt  bytea       NOT NULL,
    iterations     integer     NOT NULL CHECK (iterations >= 10000),
    disabled       boolean     NOT NULL DEFAULT false,
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- P1-1b1：角色表。只建表，不建数据库，不改 schema 属主。
--
-- 种族只存出身编号与外观：这张表里没有任何属性列，种族也就无从影响数值。
-- 职业与分支可写；分支允许为空（15 级一转才定，转身规则不在这张卡的库里）。
-- 主线场次与立仙/立魔创建时为空，服务端不写，后续主线才填。
CREATE TABLE IF NOT EXISTS "角色".character (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account     text        NOT NULL REFERENCES "角色".account (account),
    name        text        NOT NULL,
    race        text        NOT NULL,
    appearance  jsonb       NOT NULL DEFAULT '{}'::jsonb,
    class_id    text        NOT NULL,
    branch      text,
    level       integer     NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 100),
    realm       text        NOT NULL DEFAULT '炼体',
    main_stage  integer,
    alignment   text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- 同一个账号下名字不重，换个账号可以同名。
CREATE UNIQUE INDEX IF NOT EXISTS character_account_name
    ON "角色".character (account, name);

-- P1-2a：疲劳与周份额。主线进本不改这两个值，有了可比的东西才谈得上「不变」。
