-- === P1-4d crystal.sql（同一份幂等 DDL，追加进主迁移）===
-- P1-4d：能量结晶镶嵌状态与事务号。只建表，不建数据库。
--
-- 结晶跟着背包那一格装备走，不放在任何进程内存里；装备被移走或角色被删掉时，
-- 这一行跟着走，不留悬空的结晶。方案 9 章写定「可拆卸复用」：拆下时把结晶
-- 放回背包，这里只删镶嵌行，不改强化等级、不改绑定、不扣金币。
-- 镶嵌位数量是配置里的待定数值（config/crystal.json 的 socket_count），
-- 由角色服校验，库层只挡非正编号，不在 SQL 里写第二套数字。
CREATE TABLE IF NOT EXISTS "角色".crystal_socket (
    character_id    bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    slot            smallint    NOT NULL CHECK (slot BETWEEN 1 AND 200),
    socket          smallint    NOT NULL CHECK (socket > 0),
    crystal_item_id text        NOT NULL,
    -- 装上时把这一格的绑定状态一起记下，拆下时原样还回背包，不让绑定凭空消失。
    bound           boolean     NOT NULL DEFAULT false,
    bound_at        timestamptz,
    installed_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (character_id, slot, socket),
    FOREIGN KEY (character_id, slot)
        REFERENCES "角色".inventory (character_id, slot) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Q10：结晶跟着背包行走，换格不用重装。老库建的这条外键没有 ON UPDATE 动作，
-- 一改 inventory.slot（移动 / 排序只改这一列）就直接报外键冲突。这里按定义找出来
-- 重建成 ON UPDATE CASCADE：格子变了镶嵌行跟着走，编号不变。
-- 主迁移是可重跑的，所以每次跑都做一遍——已经是对的库重建一次也没有副作用。
DO $$
DECLARE item record;
BEGIN
    FOR item IN
        SELECT c.conname
          FROM pg_constraint c
         WHERE c.conrelid = '"角色".crystal_socket'::regclass
           AND c.contype = 'f'
           AND c.confrelid = '"角色".inventory'::regclass
           AND c.conname <> 'crystal_socket_inventory_fkey'
    LOOP
        EXECUTE format('ALTER TABLE "角色".crystal_socket DROP CONSTRAINT %I', item.conname);
    END LOOP;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = '"角色".crystal_socket'::regclass
           AND conname = 'crystal_socket_inventory_fkey'
    ) THEN
        ALTER TABLE "角色".crystal_socket
            ADD CONSTRAINT crystal_socket_inventory_fkey
            FOREIGN KEY (character_id, slot)
            REFERENCES "角色".inventory (character_id, slot)
            ON UPDATE CASCADE ON DELETE CASCADE;
    END IF;
END $$;

ALTER TABLE "角色".crystal_socket
    DROP CONSTRAINT IF EXISTS crystal_socket_bound_at_matches;
ALTER TABLE "角色".crystal_socket
    ADD CONSTRAINT crystal_socket_bound_at_matches
    CHECK ((bound AND bound_at IS NOT NULL) OR (NOT bound AND bound_at IS NULL));

-- 装上 / 拆下都要抢一个号：同一个号再点一次，一笔不做。
-- 号和强化、转移各自分开，避免一条链路的重放把另一条也挡掉。
CREATE TABLE IF NOT EXISTS "角色".crystal_txn (
    txn_id       text        PRIMARY KEY,
    character_id bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    slot         smallint    NOT NULL,
    socket       smallint    NOT NULL,
    action       text        NOT NULL,
    applied_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS crystal_txn_character
    ON "角色".crystal_txn (character_id, applied_at DESC);

-- === K3 craft.sql（同一份幂等 DDL，追加进主迁移）===
-- K3 生产 / 配方：进行中的一件制作与每一次制作的流水。只建表，不建数据库。
--
-- 制作的持久事实只有两样：谁手上有一件正在做、以及每一次动手成没成。
-- 材料与费用在 start 那一笔事务里就扣掉（和强化 / 转移同口径：扣减与写入同一条事务，
-- 中间失败整笔回滚，不留下「扣了材料没活」）；ready_at 到点之前 finish 只能被拒，
-- 不会提前掷成功率。成与不成各写一行 craft_log，方案 12 章的口径是「这次成没成写流水」。
--
-- 配方本身（材料 / 产出 / 费用 / 成功率 / 耗时 / 解锁）只在 config/recipes.json；
-- 这里只存「哪一条配方」与结果，不存第二份数值。成功率的掷点只在角色服、只在 finish 那一手。
CREATE TABLE IF NOT EXISTS "角色".craft_log (
    txn_id         text        PRIMARY KEY,
    character_id   bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    action         text        NOT NULL CHECK (action IN ('start', 'finish')),
    recipe_id      text        NOT NULL CHECK (recipe_id <> ''),
    profession     text        NOT NULL CHECK (profession <> ''),
    success        boolean     NOT NULL DEFAULT false,
    output_item_id text        NOT NULL DEFAULT '',
    output_count   integer     NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CHECK (output_count >= 0),
    -- 没成的那一笔必须没有产出；成了的那一笔必须有产出。
    -- start 那行也落在「没成」这一支：它只是抢号，不代表这一次制作失败。
    CHECK ((success AND output_item_id <> '' AND output_count > 0)
        OR (NOT success AND output_item_id = '' AND output_count = 0))
);

CREATE INDEX IF NOT EXISTS craft_log_character
    ON "角色".craft_log (character_id, created_at DESC);

CREATE TABLE IF NOT EXISTS "角色".craft_job (
    character_id bigint      PRIMARY KEY REFERENCES "角色".character (id) ON DELETE CASCADE,
    recipe_id    text        NOT NULL,
    start_txn_id text        NOT NULL,
    started_at   timestamptz NOT NULL DEFAULT now(),
    ready_at     timestamptz NOT NULL,
    CHECK (recipe_id <> ''),
    CHECK (start_txn_id <> ''),
    CHECK (ready_at >= started_at),
    -- 一个角色同时只做一件：主键就是「一件活」的约束，第二条 start 会被它挡住。
    -- start 那一行流水也由这里回指，删角色时两张表一起走。
    FOREIGN KEY (start_txn_id) REFERENCES "角色".craft_log (txn_id) ON DELETE CASCADE
);

