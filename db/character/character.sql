-- P1-1b1：角色表。只建表，不建数据库，不改 schema 属主。
--
-- 种族只存出身编号与外观：这张表里没有任何属性列，种族也就无从影响数值。
-- 职业与分支可写；分支允许为空（15 级一转才定，转身规则不在这张卡的库里）。
-- 主线场次与立仙/立魔创建时为空，服务端不写，后续主线才填。
CREATE TABLE IF NOT EXISTS "角色".character (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account     text        NOT NULL REFERENCES "角色".account (account),
    name        text        NOT NULL,
    race        text        NOT NULL,
    appearance  jsonb       NOT NULL DEFAULT '{}'::jsonb,
    class_id    text        NOT NULL,
    branch      text,
    level       integer     NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 100),
    realm       text        NOT NULL DEFAULT '炼体',
    main_stage  integer,
    alignment   text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- 同一个账号下名字不重，换个账号可以同名。
CREATE UNIQUE INDEX IF NOT EXISTS character_account_name
    ON "角色".character (account, name);

-- P1-2a：疲劳与周份额。主线进本不改这两个值，有了可比的东西才谈得上「不变」。
-- 深渊按人数扣疲劳、巢穴占周份额分别在 P1-2b1、P1-2c。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS fatigue integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_fatigue_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_fatigue_non_negative CHECK (fatigue >= 0);

ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS weekly_share integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_weekly_share_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_weekly_share_non_negative CHECK (weekly_share >= 0);

-- P1-2b1：疲劳是「一天」的上限，不是永久累计。记最后一次结算落在哪一天，
-- 进本时发现日界变了就先归零。日界按数据库 current_date，不另设时区配置。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS fatigue_day date NOT NULL DEFAULT CURRENT_DATE;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_fatigue_daily_cap;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_fatigue_daily_cap CHECK (fatigue <= 6000);

-- P1-2c：周份额是「这一周」的，记最后一次结算落在哪一个周首。
-- 周界按数据库 date_trunc('week', current_date)（周一为一周之始），不另设时区配置。
-- weekly_share 记的是「本周已经用掉的单人份」，每周上限 12 由 config/dungeons.json
-- 的 weekly_share_cap 给，库层只守非负：数值只有一个正本，改配置不用改约束。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS weekly_share_day date
    NOT NULL DEFAULT date_trunc('week', CURRENT_DATE::timestamp)::date;

-- P1-2d：当前等级已有经验。等级经验只由 SettleExp 这一笔写入，
-- 到 level_cap 之后不再升级；库层仍用 CHECK (level BETWEEN 1 AND 100) 兜底。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS exp bigint NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_exp_non_negative;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_exp_non_negative CHECK (exp >= 0);

-- P1-5c7：限时经验道具的剩余时间。表定义与说明在 db/character/exp_booster.sql；
-- 这里放同一份幂等 DDL，是因为 SettleExp 那一笔事务会读这张表，而只跑主迁移的
-- 老卡（P1-2d 起）也要能正常结算——表不在，它们的结算会整笔挂掉。
-- 库里只存到期时刻，不存倍率；倍率只从 config/exp_booster.json 读一个。
CREATE TABLE IF NOT EXISTS "角色".exp_booster (
    character_id bigint      PRIMARY KEY REFERENCES "角色".character (id) ON DELETE CASCADE,
    expires_at   timestamptz NOT NULL,
    used_at      timestamptz NOT NULL DEFAULT now(),
    last_txn_id  text        NOT NULL
);

-- P1-5d 的充值订单表也放进主迁移：只跑 character.sql 的一张卡里，
-- 充值那段不会因为缺表挂掉；recharge.sql 里是同一份幂等 DDL。
CREATE TABLE IF NOT EXISTS "角色".recharge_order (
    order_id     text        PRIMARY KEY,
    character_id bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    product_id   text        NOT NULL,
    yuanbao      bigint      NOT NULL CHECK (yuanbao > 0),
    status       text        NOT NULL CHECK (status IN ('pending', 'paid')),
    created_at   timestamptz NOT NULL DEFAULT now(),
    paid_at      timestamptz
);

ALTER TABLE "角色".recharge_order
    DROP CONSTRAINT IF EXISTS recharge_order_paid_at_matches;
ALTER TABLE "角色".recharge_order
    ADD CONSTRAINT recharge_order_paid_at_matches
    CHECK ((status = 'paid' AND paid_at IS NOT NULL) OR (status = 'pending' AND paid_at IS NULL));

CREATE INDEX IF NOT EXISTS recharge_order_character
    ON "角色".recharge_order (character_id, created_at);

-- P2-2a：高难本每人每周的次数按 dungeon_entry 计数（同一角色 + 同一副本 + 本周）。
-- 这张表原在 db/character/dungeon_entry.sql（P1-2a 建），而只跑主迁移的卡不会去跑
-- 那份文件——主迁移里若只放索引，全新库会报 relation does not exist。所以这里放
-- 同一份幂等 DDL：建表、reward_shares 列、两个索引，内容与 dungeon_entry.sql 一致，
-- 跑几次都不变。不加新表、不加新列。
CREATE TABLE IF NOT EXISTS "角色".dungeon_entry (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    dungeon_id   text        NOT NULL,
    party_size   integer     NOT NULL CHECK (party_size >= 1),
    entered_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE "角色".dungeon_entry
    ADD COLUMN IF NOT EXISTS reward_shares integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".dungeon_entry
    DROP CONSTRAINT IF EXISTS dungeon_entry_reward_shares_non_negative;
ALTER TABLE "角色".dungeon_entry
    ADD CONSTRAINT dungeon_entry_reward_shares_non_negative CHECK (reward_shares >= 0);

CREATE INDEX IF NOT EXISTS dungeon_entry_character
    ON "角色".dungeon_entry (character_id, entered_at DESC);

CREATE INDEX IF NOT EXISTS dungeon_entry_character_dungeon
    ON "角色".dungeon_entry (character_id, dungeon_id, entered_at DESC);

-- P2-4a：二转步数（0 未转 / 1 一转 / 2 二转）。主迁移自包含：
-- 老卡只跑 character.sql 的机器也要有这一列，否则二转与复活减免读不到。
ALTER TABLE "角色".character
    ADD COLUMN IF NOT EXISTS branch_step integer NOT NULL DEFAULT 0;
ALTER TABLE "角色".character
    DROP CONSTRAINT IF EXISTS character_branch_step_range;
ALTER TABLE "角色".character
    ADD CONSTRAINT character_branch_step_range CHECK (branch_step BETWEEN 0 AND 2);
UPDATE "角色".character
   SET branch_step = 1
 WHERE branch IS NOT NULL AND branch <> '' AND branch_step = 0;
