-- P1-1b3：背包表。只建表，不建数据库。
--
-- 一格一样东西：同角色同格子唯一，同物品要堆叠就堆在同一格里。
-- bound 与 bound_at 是绑定/非绑双轨的落点：副本装备首次拾取绑定、商城道具到账绑定，
-- 绑定物品不能直接交易（交易本身在 P1-5a）。解绑时按 bound_at 算需要的张数。
CREATE TABLE IF NOT EXISTS "角色".inventory (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    slot         smallint    NOT NULL CHECK (slot BETWEEN 1 AND 200),
    item_id      text        NOT NULL,
    count        integer     NOT NULL CHECK (count > 0),
    bound        boolean     NOT NULL DEFAULT false,
    bound_at     timestamptz,
    acquired_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (character_id, slot)
);

-- 绑定的行必须有绑定时刻，不绑的行不该有。
ALTER TABLE "角色".inventory
    DROP CONSTRAINT IF EXISTS inventory_bound_at_matches;
ALTER TABLE "角色".inventory
    ADD CONSTRAINT inventory_bound_at_matches
    CHECK ((bound AND bound_at IS NOT NULL) OR (NOT bound AND bound_at IS NULL));
