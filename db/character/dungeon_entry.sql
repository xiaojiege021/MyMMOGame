-- P1-2a：进本记录。只建表，不建数据库。
--
-- 一次进本一行，记谁、进了哪个本、当时几个人一起进。
-- 主线不扣疲劳、不占周份额，这张表只做记录；次数与份额的扣减在后面的行。
CREATE TABLE IF NOT EXISTS "角色".dungeon_entry (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    dungeon_id   text        NOT NULL,
    party_size   integer     NOT NULL CHECK (party_size >= 1),
    entered_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS dungeon_entry_character
    ON "角色".dungeon_entry (character_id, entered_at DESC);
