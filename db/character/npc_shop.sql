-- K2+Q13：NPC 商店（城镇 / 宗门）+ 出售 / 回购 / 修理。
--
-- 为什么要有这几张表：
--   · 日库存与每人限购是「会变的计数」，按配置设计的第 1 节只落库，不写 config。
--     计数按业务日（config/calendar.json 的 DayKey）分行，跨日自然归零，不需要定时任务。
--   · 回购要在卖出之后还认得出「上一次卖给这个 NPC 的是哪件、什么价」，所以单独一张表；
--     它同时是「每人每店最近 5 笔」的排序依据。
--   · 耐久是装备行的当前损耗值，挂 inventory（与强化 / 结晶同一个落点，换格不丢）。
--     NULL 表示满（未损耗），与「新建装备还没穿坏」的默认态一致，不为满耐久写一个哨兵数。
--
-- 这是分卡迁移（reapply=false，版本 31），只跑一次；主迁移 character.sql 末尾放同一份
-- 幂等 DDL，只跑主迁移的老卡也一样建得出来。已应用的版本不许原地改。

ALTER TABLE "角色".inventory
    ADD COLUMN IF NOT EXISTS durability integer;

ALTER TABLE "角色".inventory
    DROP CONSTRAINT IF EXISTS inventory_durability_non_negative;
ALTER TABLE "角色".inventory
    ADD CONSTRAINT inventory_durability_non_negative
    CHECK (durability IS NULL OR durability >= 0);

-- 当日已卖：shop_id + item_id + 业务日。库存上限在配置，已卖在库。
CREATE TABLE IF NOT EXISTS "角色".npc_shop_day (
    shop_id  text    NOT NULL,
    item_id  text    NOT NULL,
    day_key  date    NOT NULL,
    sold     integer NOT NULL DEFAULT 0 CHECK (sold >= 0),
    PRIMARY KEY (shop_id, item_id, day_key)
);

-- 每人限购：character_id + shop_id + item_id + 业务日。配置只给上限，计数在库。
CREATE TABLE IF NOT EXISTS "角色".npc_shop_purchase (
    character_id bigint  NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    shop_id      text    NOT NULL,
    item_id      text    NOT NULL,
    day_key      date    NOT NULL,
    bought       integer NOT NULL DEFAULT 0 CHECK (bought >= 0),
    PRIMARY KEY (character_id, shop_id, item_id, day_key)
);

-- 回购：卖出时记一行，回购后写 bought_back_at，不删行（核对要看得到流水）。
CREATE TABLE IF NOT EXISTS "角色".npc_shop_buyback (
    id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id   bigint      NOT NULL REFERENCES "角色".character (id) ON DELETE CASCADE,
    shop_id        text        NOT NULL,
    item_id        text        NOT NULL,
    count          integer     NOT NULL CHECK (count > 0),
    unit_price     integer     NOT NULL CHECK (unit_price >= 0),
    sold_at        timestamptz NOT NULL DEFAULT now(),
    bought_back_at timestamptz
);

CREATE INDEX IF NOT EXISTS npc_shop_buyback_live
    ON "角色".npc_shop_buyback (character_id, shop_id, sold_at DESC);
