#!/usr/bin/env python3
"""客户端界面文案表（D9）。

正本：config/ui_text/<组>.json   每条形如 {"key": "T001", "text": "背包"}
生成：client/MMOGame/Assets/HotUpdate/Ui/UiStrings/<组>.cs
      （namespace HotUpdate.Ui / static partial class UiStrings / 嵌套静态类 <组>）

组 = 源文件的 basename（`UiBagScreen.cs` → `BagScreen`，`Ui/Flow/ArenaFlow.cs` → `ArenaFlow`）。

用法：
  python3 tools/gen/gen-ui-text.py              # 生成全部 UiStrings 分片（读 JSON，不碰源码）
  python3 tools/gen/gen-ui-text.py --out DIR    # 生成到别处（核对 / 演练用）
  python3 tools/gen/gen-ui-text.py --rewrite    # 一次性迁移：扫源码中文串 → 补 JSON → 改源码 → 生成
  python3 tools/gen/gen-ui-text.py --report     # 只报告：源码里还有几处中文串没进表
  python3 tools/gen/gen-ui-text.py --root R --out DIR   # 用 R 下的 config 生成（改文案演练）

为什么不是运行期加载：热更程序集不引字典泛型（真机 MissingMethodException），
文案一律编译期常量；`case` 标签与属性参数也要能用，所以生成为 const string。
为什么不是手写 C# 常量夹文案：改一句话要动代码；这里文案只在 config，改完重跑本脚本。
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLIENT = "client/MMOGame/Assets/HotUpdate"
CONFIG = "config/ui_text"
OUT = "client/MMOGame/Assets/HotUpdate/Ui/UiStrings"

# 生成物 / 别处正本：不参与扫描，也不许被改写。
SKIP_FILES = {
    "Ui/UiContentTable.cs",      # K6 / C5：从 config/dialogue 生成，正本不在本卡
}
SKIP_DIRS = {"Ui/UiStrings"}
CN = re.compile(r"[\u4e00-\u9fff]")


# ---------------------------------------------------------------- 扫描

def scan(path):
    """返回 [(start, end, body)]：含中文的普通字符串字面量（不含插值 / verbatim）。"""
    src = open(path, encoding="utf-8").read()
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c == "/" and i + 1 < n and src[i + 1] == "/":
            j = src.find("\n", i)
            i = n if j < 0 else j
            continue
        if c == "/" and i + 1 < n and src[i + 1] == "*":
            j = src.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        if c == "'":
            j = i + 1
            while j < n:
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == "'":
                    j += 1
                    break
                j += 1
            i = j
            continue
        if c in '$@"':
            start, prefix = i, ""
            while i < n and src[i] in "$@":
                prefix += src[i]
                i += 1
            if i >= n or src[i] != '"':
                i = start + 1
                continue
            if prefix:
                # 插值 / verbatim 不在本卡口径内：出现即报错，别悄悄漏搬。
                raise SystemExit("%s 出现 %s\" 字面量，本脚本只支持普通字符串" % (path, prefix))
            i += 1
            body_start = i
            while i < n:
                if src[i] == "\\":
                    i += 2
                    continue
                if src[i] == '"':
                    break
                i += 1
            body = src[body_start:i]
            i += 1
            if CN.search(body):
                out.append((start, i, body))
            continue
        i += 1
    return out


def sources(root):
    """[(rel, group, path)]：参与搬运的源文件。"""
    base = os.path.join(root, CLIENT)
    rows = []
    for dirpath, dirs, files in os.walk(base):
        rel_dir = os.path.relpath(dirpath, base).replace(os.sep, "/")
        if rel_dir in SKIP_DIRS:
            continue
        for f in sorted(files):
            if not f.endswith(".cs"):
                continue
            rel = f if rel_dir == "." else rel_dir + "/" + f
            if rel in SKIP_FILES:
                continue
            rows.append((rel, f[:-3], os.path.join(dirpath, f)))
    rows.sort()
    return rows


# ---------------------------------------------------------------- 正本

def group_path(root, group):
    return os.path.join(root, CONFIG, group + ".json")


def load_group(root, group, src):
    p = group_path(root, group)
    if os.path.exists(p):
        data = json.load(open(p, encoding="utf-8"))
    else:
        data = {"schema": "ui-text/1", "group": group,
                "source": "%s/%s" % (CLIENT, src), "entries": []}
    return data


def save_group(root, group, data):
    p = group_path(root, group)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    body = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    with open(p, "w", encoding="utf-8") as f:
        f.write(body)


# ---------------------------------------------------------------- 生成

def cs_escape(body):
    """body 是源码里引号之间的原文（转义序列已按源码形态保留），原样放回即可。"""
    return body


def emit_group(data, outdir):
    group, src = data["group"], data.get("source", "")
    lines = [
        "// <auto-generated>",
        "// 由 tools/gen/gen-ui-text.py 从 config/ui_text/%s.json 生成，不要手改。" % group,
        "// 源文件：%s" % src,
        "// 改文案：改配置后重跑 python3 tools/gen/gen-ui-text.py，引用处不用动。",
        "// </auto-generated>",
        "",
        "namespace HotUpdate.Ui",
        "{",
        "    public static partial class UiStrings",
        "    {",
        "        /// <summary>%s 的界面文案。</summary>" % src,
        "        public static class %s" % group,
        "        {",
    ]
    for e in data["entries"]:
        text = e["text"].replace("\n", "\\n")
        lines.append('            public const string %s = "%s";' % (e["key"], cs_escape(text)))
    lines += ["        }", "    }", "}", ""]
    path = os.path.join(outdir, group + ".cs")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def emit_all(root, outdir):
    src_dir = os.path.join(root, CONFIG)
    if not os.path.isdir(src_dir):
        raise SystemExit("缺少配置目录：" + CONFIG)
    os.makedirs(outdir, exist_ok=True)
    groups = []
    for f in sorted(os.listdir(src_dir)):
        if not f.endswith(".json"):
            continue
        data = json.load(open(os.path.join(src_dir, f), encoding="utf-8"))
        emit_group(data, outdir)
        groups.append(data["group"])
    return groups


# ---------------------------------------------------------------- 迁移

def next_key(entries):
    used = {e["key"] for e in entries}
    n = len(entries) + 1
    while "T%03d" % n in used:
        n += 1
    return "T%03d" % n


def rewrite(root):
    """扫源码 → 补 JSON → 把字面量换成常量引用。幂等：已换过的地方不再是字面量。"""
    touched, added = 0, 0
    for rel, group, path in sources(root):
        lits = scan(path)
        if not lits:
            continue
        data = load_group(root, group, rel)
        by_text = {e["text"]: e["key"] for e in data["entries"]}
        src = open(path, encoding="utf-8").read()
        # 先按出现顺序定 key（JSON 序号与源码同序），再从后往前替换（偏移不失效）
        plan = []
        for start, end, body in lits:
            key = by_text.get(body)
            if key is None:
                key = next_key(data["entries"])
                data["entries"].append({"key": key, "text": body})
                by_text[body] = key
                added += 1
            plan.append((start, end, key))
        for start, end, key in reversed(plan):
            src = src[:start] + "UiStrings.%s.%s" % (group, key) + src[end:]
            touched += 1
        open(path, "w", encoding="utf-8").write(src)
        save_group(root, group, data)
    return touched, added


def report(root):
    left = []
    for rel, group, path in sources(root):
        for start, end, body in scan(path):
            left.append((rel, body))
    print("源码里还没进表的中文串：%d 处" % len(left))
    for rel, body in left[:20]:
        print("  %s  %s" % (rel, body))
    return len(left)


# ---------------------------------------------------------------- 入口

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--out", default=None)
    ap.add_argument("--rewrite", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    root = os.path.abspath(a.root)

    if a.report:
        raise SystemExit(1 if report(root) else 0)
    if a.rewrite:
        touched, added = rewrite(root)
        print("改写 %d 处，新增 %d 条" % (touched, added))
        outdir = os.path.join(root, OUT)
        groups = emit_all(root, outdir)
        print("生成 %d 组分片 → %s" % (len(groups), OUT))
        return
    outdir = os.path.abspath(a.out) if a.out else os.path.join(root, OUT)
    groups = emit_all(root, outdir)
    print("生成 %d 组分片 → %s" % (len(groups), outdir))


if __name__ == "__main__":
    main()
